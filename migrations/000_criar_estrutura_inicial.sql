
BEGIN;

CREATE TABLE public.clientes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nome VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL,
    telefone VARCHAR(20),
    cpf VARCHAR(11),
    senha_hash VARCHAR(255),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT clientes_pkey PRIMARY KEY (id),
    CONSTRAINT clientes_email_key UNIQUE (email),
    CONSTRAINT clientes_cpf_key UNIQUE (cpf),
    CONSTRAINT chk_clientes_cpf
        CHECK (cpf IS NULL OR cpf ~ '^[0-9]{11}$'),
    CONSTRAINT chk_clientes_email
        CHECK (POSITION('@' IN email) > 1),
    CONSTRAINT chk_clientes_nome
        CHECK (LENGTH(BTRIM(nome)) >= 3)
);

CREATE TABLE public.produtos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nome VARCHAR(100) NOT NULL,
    categoria VARCHAR(50) NOT NULL,
    preco NUMERIC(10, 2) NOT NULL,
    estoque INTEGER NOT NULL DEFAULT 0,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT produtos_pkey PRIMARY KEY (id),
    CONSTRAINT chk_produtos_estoque
        CHECK (estoque >= 0),
    CONSTRAINT chk_produtos_preco
        CHECK (preco > 0)
);

CREATE TABLE public.pedidos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    cliente_id INTEGER NOT NULL,
    data_pedido TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(20) NOT NULL DEFAULT 'pendente',
    valor_total NUMERIC(12, 2) NOT NULL DEFAULT 0,

    CONSTRAINT pedidos_pkey PRIMARY KEY (id),
    CONSTRAINT fk_pedidos_clientes
        FOREIGN KEY (cliente_id)
        REFERENCES public.clientes(id),
    CONSTRAINT chk_pedidos_status
        CHECK (
            status IN (
                'pendente',
                'pago',
                'enviado',
                'entregue',
                'cancelado'
            )
        ),
    CONSTRAINT chk_pedidos_valor
        CHECK (valor_total >= 0)
);

CREATE TABLE public.itens_pedido (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    pedido_id INTEGER NOT NULL,
    produto_id INTEGER NOT NULL,
    quantidade INTEGER NOT NULL,
    preco_unitario NUMERIC(10, 2) NOT NULL,
    subtotal NUMERIC(12, 2)
        GENERATED ALWAYS AS (
            quantidade * preco_unitario
        ) STORED,

    CONSTRAINT itens_pedido_pkey PRIMARY KEY (id),
    CONSTRAINT uq_pedido_produto
        UNIQUE (pedido_id, produto_id),
    CONSTRAINT fk_itens_pedido
        FOREIGN KEY (pedido_id)
        REFERENCES public.pedidos(id),
    CONSTRAINT fk_itens_produto
        FOREIGN KEY (produto_id)
        REFERENCES public.produtos(id),
    CONSTRAINT chk_itens_quantidade
        CHECK (quantidade > 0),
    CONSTRAINT chk_itens_preco
        CHECK (preco_unitario > 0)
);

COMMIT;
