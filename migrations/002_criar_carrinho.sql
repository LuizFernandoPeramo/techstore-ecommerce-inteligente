
BEGIN;

CREATE TABLE IF NOT EXISTS carrinhos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id INTEGER NOT NULL UNIQUE,
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_carrinhos_clientes
        FOREIGN KEY (cliente_id)
        REFERENCES clientes(id)
        ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS itens_carrinho (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    carrinho_id INTEGER NOT NULL,
    produto_id INTEGER NOT NULL,
    quantidade INTEGER NOT NULL,
    adicionado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_itens_carrinho_carrinhos
        FOREIGN KEY (carrinho_id)
        REFERENCES carrinhos(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_itens_carrinho_produtos
        FOREIGN KEY (produto_id)
        REFERENCES produtos(id),

    CONSTRAINT uq_itens_carrinho_produto
        UNIQUE (carrinho_id, produto_id),

    CONSTRAINT ck_itens_carrinho_quantidade
        CHECK (quantidade > 0)
);

CREATE INDEX IF NOT EXISTS idx_itens_carrinho_produto
    ON itens_carrinho(produto_id);

COMMIT;
